const LanguageContext = createContext(null)
const originalText = new WeakMap()
const originalAttributes = new WeakMap()

function translateTextNodes(language) {
  const dictionary = { ...(translations[language] || {}), ...(additionalTranslations[language] || {}) }
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT)
  const nodes = []

  while (walker.nextNode()) {
    const node = walker.currentNode
    const parent = node.parentElement
    if (!parent || ['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(parent.tagName)) continue
    if (parent.closest('[data-language-menu], [data-language-ignore]')) continue
    nodes.push(node)
  }

  nodes.forEach((node) => {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue)
    const source = originalText.get(node)
    const trimmed = source.trim()
    const translated = dictionary[trimmed]
    node.nodeValue = translated ? source.replace(trimmed, translated) : source
  })

  document.querySelectorAll('input, textarea, img, button, [aria-label], [title]').forEach((element) => {
    if (element.closest('[data-language-menu], [data-language-ignore]')) return
    if (!originalAttributes.has(element)) originalAttributes.set(element, {})
    const attributes = originalAttributes.get(element)
    ;['placeholder', 'alt', 'aria-label', 'title'].forEach((name) => {
      if (!element.hasAttribute(name)) return
      if (!attributes[name]) attributes[name] = element.getAttribute(name)
      const source = attributes[name]
      element.setAttribute(name, dictionary[source] || source)
    })
  })
}

export function LanguageProvider({ children }) {
  const location = useLocation()
  const [language, setLanguage] = useState(() => localStorage.getItem('zeno-language') || 'it')

  useEffect(() => {
    localStorage.setItem('zeno-language', language)
    const frame = requestAnimationFrame(() => translateTextNodes(language))
    return () => cancelAnimationFrame(frame)
  }, [language, location.pathname, location.search])

  const value = useMemo(() => ({
    language,
    setLanguage,
    languages,
    t: (text) => translations[language]?.[text] || additionalTranslations[language]?.[text] || text,
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

